class Command(BaseCommand):
    help = "Заполняет справочник стран и городов"

    def handle(self, *args, **options):
        countries_created = 0
        cities_created = 0

        for country_name, city_names in LOCATIONS.items():
            country, created = Country.objects.get_or_create(
                name=country_name
            )

            if created:
                countries_created += 1

            for city_name in city_names:
                _, created = City.objects.get_or_create(
                    country=country,
                    name=city_name,
                )

                if created:
                    cities_created += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово. Добавлено стран: {countries_created}, "
                f"городов: {cities_created}."
            )
        )